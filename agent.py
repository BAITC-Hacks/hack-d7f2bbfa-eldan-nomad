def norm_cdf(x: float) -> float:
    """CDF стандартного нормального распределения через math.erf (обрабатывает +-inf)."""
    if x != x:  # NaN
        return 0.5
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


