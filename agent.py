@dataclass
class AnalystDeps:
    """Read-only снимок для инструментов HypothesisAnalyst."""

    batch_ids: list[str]
    items: dict[str, dict]  # arm_id -> элемент
    tariffs: dict[str, dict]
    cells: dict[str, dict] = field(default_factory=dict)  # "from|seg" -> агрегаты


@dataclass
class ReviewDeps:
    """Read-only снимок для инструментов RiskReviewer."""

    campaign_names: list[str]
    campaigns: dict[str, dict]
    evidence: dict[str, dict]
    p_pos: dict[str, float]
    what_if: Callable[[list[str]], dict]


def _llm_cells_from_items(items: list[dict]) -> dict[str, dict]:
    """Агрегирует элементы батча по ячейкам 'from|seg'."""
    cells: dict[str, dict] = {}
    for it in items:
        try:
            a = parse_arm_id(str(it.get("arm_id")))
        except ValueError:
            continue
        cid = f"{a[0]}|{a[1]}"
        c = cells.setdefault(cid, {"cell_id": cid, "targets": []})
        c["targets"].append(a[2])
        for k in ("n", "sum_p", "cell_n", "cell_sum_p", "mean_p"):
            if k in it and k not in c:
                c[k] = it[k]
    for c in cells.values():
        c["targets"] = sorted(set(c["targets"]))
    return cells


def _llm_tariff_price(t: dict) -> Optional[float]:
    """Месячная цена из строки тарифа, если есть."""
    for k in ("price_tariff", "price", "monthly_fee"):
        if k in t:
            try:
                return float(t[k])
            except (TypeError, ValueError):
                return None
    return None


